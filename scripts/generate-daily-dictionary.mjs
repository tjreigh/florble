import { readFileSync, writeFileSync } from 'node:fs';

import wordListPath from 'word-list';

const outputUrl = new URL('../src/content/daily/generated-accepted-guesses.ts', import.meta.url);
const words = [...new Set(
  readFileSync(wordListPath, 'utf8')
    .split('\n')
    .filter((word) => /^[a-z]{5}$/.test(word))
    .map((word) => word.toUpperCase()),
)].sort();

const lines = [];
for (let index = 0; index < words.length; index += 14) {
  lines.push(words.slice(index, index + 14).join(' '));
}

const generated = `// Generated by yarn content:generate from word-list 4.1.0 (MIT).
// Do not edit this file directly. See THIRD_PARTY_NOTICES.md.
const GENERATED_ACCEPTED_GUESS_SOURCE = \`
${lines.join('\n')}
\`;

export const GENERATED_ACCEPTED_GUESSES: readonly string[] = Object.freeze(
  GENERATED_ACCEPTED_GUESS_SOURCE.trim().split(/\\s+/),
);
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outputUrl, 'utf8');
  } catch {
    // The comparison below reports the actionable error.
  }
  if (current !== generated) {
    throw new Error('Daily dictionary is stale. Run yarn content:generate.');
  }
} else {
  writeFileSync(outputUrl, generated);
  console.log(`Generated ${words.length} accepted five-letter words.`);
}
